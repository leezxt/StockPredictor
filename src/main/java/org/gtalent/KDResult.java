package org.gtalent;

public class KDResult {
    private double k;
    private double d;

    public KDResult(double k, double d) {
        this.k = k;
        this.d = d;
    }

    public double getK() {
        return k;
    }

    public void setK(double k) {
        this.k = k;
    }

    public double getD() {
        return d;
    }

    public void setD(double d) {
        this.d = d;
    }
}

