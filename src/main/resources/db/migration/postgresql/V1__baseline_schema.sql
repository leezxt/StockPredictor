CREATE TABLE STOCK_DATA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    trade_date DATE NOT NULL,
    open_price NUMERIC(10, 2),
    high_price NUMERIC(10, 2),
    low_price NUMERIC(10, 2),
    close_price NUMERIC(10, 2),
    volume BIGINT,
    price NUMERIC(10, 2),
    foreign_buy BIGINT,
    trust_buy BIGINT,
    dealer_buy BIGINT,
    CONSTRAINT UK_STOCK_DATA_SYMBOL_DATE UNIQUE (symbol, trade_date)
);
CREATE INDEX IDX_SYMBOL_DATE ON STOCK_DATA(symbol, trade_date);

CREATE TABLE STOCK_UNIVERSE (
    symbol VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) DEFAULT '',
    market VARCHAR(20) DEFAULT '',
    asset_type VARCHAR(30) DEFAULT 'UNKNOWN',
    is_etf BOOLEAN DEFAULT FALSE,
    active BOOLEAN DEFAULT TRUE,
    last_synced_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE INSTITUTIONAL_DATA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    trade_date DATE NOT NULL,
    foreign_buy BIGINT DEFAULT 0,
    trust_buy BIGINT DEFAULT 0,
    dealer_buy BIGINT DEFAULT 0,
    CONSTRAINT UK_INSTITUTIONAL_SYMBOL_DATE UNIQUE (symbol, trade_date)
);

CREATE TABLE SCAN_HISTORY (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    scan_date DATE NOT NULL,
    score INT NOT NULL,
    price_at_scan DOUBLE PRECISION NOT NULL,
    rsi_at_scan DOUBLE PRECISION
);

CREATE TABLE MARKET_BREADTH (
    trade_date DATE PRIMARY KEY,
    breadth NUMERIC(5, 2) NOT NULL,
    eligible_count INT NOT NULL,
    bullish_count INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE MONTHLY_REVENUE (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    year_month VARCHAR(7) NOT NULL,
    revenue DOUBLE PRECISION NOT NULL,
    mom DOUBLE PRECISION DEFAULT 0,
    yoy DOUBLE PRECISION DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_MONTHLY_REVENUE_SYMBOL_MONTH UNIQUE (symbol, year_month)
);

CREATE TABLE FINMIND_SHAREHOLDING (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    trade_date DATE NOT NULL,
    holding_factor INT NOT NULL,
    shareholder_count INT NOT NULL,
    shares BIGINT NOT NULL,
    percentage DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_SHAREHOLDING_SYMBOL_DATE_FACTOR
        UNIQUE (symbol, trade_date, holding_factor)
);

CREATE TABLE FINMIND_DAY_TRADING (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    trade_date DATE NOT NULL,
    buy_amount BIGINT DEFAULT 0,
    sell_amount BIGINT DEFAULT 0,
    day_trading_volume BIGINT DEFAULT 0,
    day_trading_rate DOUBLE PRECISION DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_DAY_TRADING_SYMBOL_DATE UNIQUE (symbol, trade_date)
);

CREATE TABLE APP_META (
    meta_key VARCHAR(100) PRIMARY KEY,
    meta_value VARCHAR(500) NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE FINANCIAL_QUARTER_DATA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    quarter_date DATE NOT NULL,
    gross_profit_margin DOUBLE PRECISION DEFAULT 0,
    operating_profit_margin DOUBLE PRECISION DEFAULT 0,
    net_profit_margin DOUBLE PRECISION DEFAULT 0,
    inventory_turnover_days INT DEFAULT 0,
    contract_liabilities BIGINT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_FINANCIAL_QUARTER_SYMBOL_DATE UNIQUE (symbol, quarter_date)
);
